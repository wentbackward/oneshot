#!/usr/bin/env python3
"""Post-merge extraction audit.

Compares the verbatim parses (source of truth) against the rewritten
entries and the merged game-data catalogs; writes a human-readable
EXTRACTION-REPORT.md. Exit 0 = complete, 1 = incomplete (so a CI-style
watcher can act on it). Std lib only.
"""
import json
import sys
import collections
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRIVATE = ROOT / "private" / "dnd"
GAME_DATA = ROOT / "game-data"
sys.path.insert(0, str(Path(__file__).resolve().parent))
from dnd_extract import BOOKS  # noqa: E402

# Must mirror rewrite_args() in dnd_supervise.sh.
SCOPE = {
    "phb2024": None,                     # all kinds (canon)
    "dmg": ["magic_item", "monster"],    # items + reference monsters
    "mm": ["monster", "magic_item"],     # bestiary
    "phb2014": None,                     # parse archived; rewrite skipped
}
SKIP_BOOKS = {"phb2014"}


def main() -> None:
    ok = True
    out = ["# Extraction Report",
           "",
           "Generated by `scripts/dnd_audit.py` — run manually or after the",
           "supervisor's merge phase. Coverage = rewritten / in-scope candidates.",
           ""]

    for book in ("phb2024", "dmg", "mm", "phb2014"):
        out.append(f"## {book}")
        vp = PRIVATE / "verbatim" / f"{book}.jsonl"
        if not vp.exists():
            out.append("- no verbatim data found")
            continue
        kinds = SCOPE[book] if SCOPE[book] is not None else BOOKS[book]["kinds"]
        c = collections.Counter()
        cand = set()
        for ln in open(vp, encoding="utf-8"):
            r = json.loads(ln)
            for i, e in enumerate(r.get("entries", [])):
                if e.get("kind") in kinds:
                    c[e["kind"]] += 1
                    cand.add((r.get("_page"), i))
        total = len(cand)
        if book in SKIP_BOOKS:
            out.append(f"- SKIPPED by owner (2024 PHB is sufficient); "
                       f"{sum(c.values())} parsed entries archived only.")
            out.append("")
            continue
        rew_path = PRIVATE / "rewritten" / f"{book}-all.jsonl"
        covered_set = set()
        lines = 0
        if rew_path.exists():
            for ln in open(rew_path, encoding="utf-8"):
                if not ln.strip():
                    continue
                lines += 1
                try:
                    dd = json.loads(ln)
                except Exception:  # noqa: BLE001
                    continue
                covered_set.add((dd.get("_source_page"), dd.get("_source_idx")))
        covered = len(covered_set & cand)
        cov = 100.0 * covered / total if total else 100.0
        if total and covered < total:
            ok = False
        out.append(f"- in-scope candidates: **{total}**  {dict(c.most_common())}")
        out.append(f"- rewritten entries on disk: **{lines}** "
                   f"(unique candidates covered: **{covered}**, "
                   f"coverage {cov:.1f}%)")
        vf = PRIVATE / "validation" / f"{book}-problems.txt"
        if vf.exists():
            hard = [l for l in vf.read_text(encoding="utf-8").splitlines()
                    if l.strip() and "EXTRA(info)" not in l]
            out.append(f"- open hard validation problems: **{len(hard)}**")
            for l in hard[:10]:
                out.append("  - " + l)
        out.append("")

    out.append("## game-data inventory (merged output)")
    for f in sorted(GAME_DATA.glob("*.json")):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
            n = len(data) if isinstance(data, (list, dict)) else "unknown shape"
        except Exception as ex:  # noqa: BLE001
            n = f"INVALID JSON ({ex})"
            ok = False
        out.append(f"- `{f.name}`: {n} entries")
    out.append("")

    # Merged-catalog completeness: what the catalogs CONTAIN must equal what
    # merge is entitled to write (union over books, minus flagged ids). This
    # is the check that would have caught a clobbering merge even while
    # rewrite coverage reads 100%.
    out.append("## merged-catalog completeness")
    kinds_all = ("spell", "weapon", "armor", "gear", "magic_item",
                "monster", "feat", "background", "race")
    per_book_flagged = {}
    for book in ("phb2024", "dmg", "mm"):
        vf = PRIVATE / "validation" / f"{book}-problems.txt"
        if vf.exists():
            per_book_flagged[book] = {
                l.partition(":")[0].strip()
                for l in vf.read_text(encoding="utf-8").splitlines()
                if l.strip() and "EXTRA(info)" not in l}
        else:
            per_book_flagged[book] = set()
    expected = {k: set() for k in kinds_all}
    for book in ("phb2024", "dmg", "mm"):
        rp = PRIVATE / "rewritten" / f"{book}-all.jsonl"
        if not rp.exists():
            continue
        for ln in open(rp, encoding="utf-8"):
            if not ln.strip():
                continue
            try:
                d = json.loads(ln)
            except Exception:  # noqa: BLE001
                continue
            k, i = d.get("kind"), d.get("id")
            if k in expected and i and i not in per_book_flagged[book]:
                expected[k].add(i)
    for k in kinds_all:
        fp = GAME_DATA / f"{k}.json"
        if fp.exists():
            try:
                actual = {e.get("id") for e in
                          json.loads(fp.read_text(encoding="utf-8"))}
            except Exception:  # noqa: BLE001
                out.append(f"- `{k}.json`: INVALID — MISMATCH")
                ok = False
                continue
        else:
            actual = set()
        missing, extra = expected[k] - actual, actual - expected[k]
        line = f"- `{k}.json`: {len(actual)}/{len(expected[k])} expected"
        if missing:
            line += f" — MISSING {len(missing)} (e.g. " \
                    f"{', '.join(sorted(missing)[:4])})"
        if extra:
            line += f" — UNEXPECTED {len(extra)}"
        if missing or extra:
            ok = False
            line += "  [MISMATCH]"
        out.append(line)
    out.append("")

    report = "\n".join(out) + f"\n\n**Result: {'COMPLETE' if ok else 'INCOMPLETE'}**\n"
    (PRIVATE / "EXTRACTION-REPORT.md").write_text(report, encoding="utf-8")
    print(f"report -> private/dnd/EXTRACTION-REPORT.md "
          f"({'COMPLETE' if ok else 'INCOMPLETE'})")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
